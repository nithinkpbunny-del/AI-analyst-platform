#!/usr/bin/env python3
"""Derive docker-compose-only variables from ``.env`` and write them to ``.compose.env``.

``.env`` holds values for running tools on your computer (``localhost``). Containers reach each other by service
name (``postgres``, ``redis``), and the Postgres container needs its user/password/database as separate variables.
This script reads ``DATABASE_URL`` / ``REDIS_URL`` and writes:

    POSTGRES_USER, POSTGRES_PASSWORD, POSTGRES_DB   (for the postgres container)
    CONTAINER_DATABASE_URL, CONTAINER_REDIS_URL     (the same URLs with the host replaced by the service name)

Secrets are written only to ``.compose.env`` (git-ignored, mode 600) and are never printed.
Standard library only, so it runs with any Python 3.
"""

from __future__ import annotations

import os
import sys
from pathlib import Path
from urllib.parse import unquote, urlsplit, urlunsplit

ROOT = Path(__file__).resolve().parent.parent


def read_env(path: Path) -> dict[str, str]:
    values: dict[str, str] = {}
    for raw in path.read_text(encoding="utf-8").splitlines():
        line = raw.strip()
        if not line or line.startswith("#") or "=" not in line:
            continue
        key, _, value = line.partition("=")
        value = value.strip()
        if value[:1] in ("'", '"'):  # quoted: take what is inside the quotes
            value = value[1:].split(value[0], 1)[0]
        else:  # unquoted: " # comment" at the end is a comment, like in docker compose and python-dotenv
            value = value.split(" #", 1)[0].strip()
        values[key.strip()] = value
    return values


def with_host(url: str, host: str, port: int | None = None) -> str:
    parts = urlsplit(url)
    userinfo = parts.netloc.rpartition("@")[0]
    netloc = f"{userinfo}@" if userinfo else ""
    netloc += host
    port = port or parts.port
    if port:
        netloc += f":{port}"
    return urlunsplit((parts.scheme, netloc, parts.path, parts.query, parts.fragment))


def main() -> int:
    env_path = ROOT / ".env"
    if not env_path.exists():
        print("No .env file found. Create it first:  cp .env.example .env  (then fill in your values)",
              file=sys.stderr)
        return 1
    env = read_env(env_path)
    missing = [k for k in ("DATABASE_URL", "REDIS_URL", "S3_ACCESS_KEY", "S3_SECRET_KEY") if not env.get(k)]
    if missing:
        print(f"These variables are missing or empty in .env: {', '.join(missing)}", file=sys.stderr)
        return 1

    db = urlsplit(env["DATABASE_URL"])
    if not (db.username and db.password and db.path.strip("/")):
        print("DATABASE_URL must look like postgresql+psycopg://user:password@localhost:5432/dbname",
              file=sys.stderr)
        return 1
    lines = {
        "POSTGRES_USER": unquote(db.username),
        "POSTGRES_PASSWORD": unquote(db.password),
        "POSTGRES_DB": db.path.strip("/"),
        "CONTAINER_DATABASE_URL": with_host(env["DATABASE_URL"], "postgres", 5432),
        "CONTAINER_REDIS_URL": with_host(env["REDIS_URL"], "redis", 6379),
    }
    for key, value in lines.items():
        if "'" in value or "\n" in value:
            print(f"The value derived for {key} contains a quote or newline, which docker compose cannot "
                  "read safely. Use a password without quotes.", file=sys.stderr)
            return 1
    target = ROOT / ".compose.env"
    fd = os.open(target, os.O_WRONLY | os.O_CREAT | os.O_TRUNC, 0o600)
    with os.fdopen(fd, "w", encoding="utf-8") as handle:
        handle.write("# Generated by scripts/compose_env.py from .env. Do not edit or commit.\n")
        for key, value in lines.items():
            handle.write(f"{key}='{value}'\n")  # single quotes: compose takes the value literally
    os.chmod(target, 0o600)
    print("Wrote .compose.env (derived from .env)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
