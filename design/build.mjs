#!/usr/bin/env node
// Generates design/generated/tokens.css (CSS variables, light + dark) and design/generated/tailwind-theme.css
// (the Tailwind v4 "preset": an @theme block mapping utilities to the variables) from design/tokens.json.
// Usage: node design/build.mjs [--check]   (--check fails if the committed files are out of date)

import { readFileSync, writeFileSync, mkdirSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const HEADER = '/* Generated by design/build.mjs from design/tokens.json. Do not edit by hand. */\n'

const block = (selector, lines) => `${selector} {\n${lines.map((l) => `  ${l}`).join('\n')}\n}\n`
const fontList = (names) => names.map((n) => (n.includes(' ') ? `"${n}"` : n)).join(', ')

function themeVars(tokens, mode) {
  const vars = Object.entries(tokens.color[mode]).map(([name, value]) => `--${name}: ${value};`)
  tokens.chart[mode].forEach((value, i) => vars.push(`--chart-${i + 1}: ${value};`))
  vars.push(`--haldi-mark-opacity: ${tokens.haldiMarkOpacity[mode]};`)
  vars.push(`--overlay-shadow: ${tokens.shadow[mode].overlay};`)
  vars.push(`--scrim: ${tokens.scrim[mode]};`)
  vars.push(`color-scheme: ${mode};`)
  return vars
}

export function buildTokensCss(tokens) {
  const shared = [
    `--font-display: ${fontList(tokens.font.display)};`,
    `--font-body: ${fontList(tokens.font.body)};`,
    ...Object.entries(tokens.fontSize).map(([k, v]) => `--text-${k}: ${v};`),
    ...Object.entries(tokens.lineHeight).map(([k, v]) => `--leading-${k}: ${v};`),
    `--tracking-display: ${tokens.letterSpacing.display};`,
    ...Object.entries(tokens.radius).map(([k, v]) => `--radius-${k}: ${v};`),
    ...Object.entries(tokens.space).map(([k, v]) => `--space-${k}: ${v};`),
    ...Object.entries(tokens.size).map(([k, v]) => `--size-${k}: ${v};`),
    `--duration-fade: ${tokens.motion.fade};`,
    `--duration-drawer: ${tokens.motion.drawer};`,
    `--duration-sweep: ${tokens.motion.sweep};`,
    `--ease-out: ${tokens.motion.easeOut};`,
  ]
  const light = themeVars(tokens, 'light')
  const dark = themeVars(tokens, 'dark')
  return [
    HEADER,
    '/* Light is the default; dark follows the system unless the user picked light, or is forced with data-theme="dark". */\n',
    block(':root', [...shared, ...light]),
    '\n@media (prefers-color-scheme: dark) {\n' +
      block(':root:not([data-theme="light"])', dark)
        .split('\n')
        .map((l) => (l ? `  ${l}` : l))
        .join('\n') +
      '}\n',
    '\n' + block(':root[data-theme="dark"]', dark),
  ].join('')
}

export function buildTailwindTheme(tokens) {
  const colors = Object.keys(tokens.color.light).map((n) => `--color-${n}: var(--${n});`)
  const chart = tokens.chart.light.map((_, i) => `--color-chart-${i + 1}: var(--chart-${i + 1});`)
  const lines = [
    '/* Reset Tailwind defaults so only design tokens can be used (no stray colours, fonts or radii). */',
    '--color-*: initial;',
    '--font-*: initial;',
    '--radius-*: initial;',
    '--shadow-*: initial;',
    '--text-*: initial;',
    '--breakpoint-*: initial;',
    ...colors,
    ...chart,
    '--color-scrim: var(--scrim);',
    // Mode-independent tokens are written as values (same names as tokens.css, so no var() cycles).
    `--font-display: ${fontList(tokens.font.display)};`,
    `--font-sans: ${fontList(tokens.font.body)};`,
    ...Object.entries(tokens.fontSize).map(([k, v]) => `--text-${k}: ${v};`),
    ...Object.entries(tokens.radius).map(([k, v]) => `--radius-${k}: ${v};`),
    '--shadow-overlay: var(--overlay-shadow);',
    `--container-prose: ${tokens.size.prose};`,
    `--container-conversation: ${tokens.size.conversation};`,
    ...Object.entries(tokens.breakpoint).map(([k, v]) => `--breakpoint-${k}: ${v};`),
    '--spacing: 4px;',
  ]
  return HEADER + '@theme inline {\n' + lines.map((l) => `  ${l}`).join('\n') + '\n}\n'
}

export function loadTokens() {
  return JSON.parse(readFileSync(join(here, 'tokens.json'), 'utf8'))
}

export function outputs(tokens = loadTokens()) {
  return {
    'generated/tokens.css': buildTokensCss(tokens),
    'generated/tailwind-theme.css': buildTailwindTheme(tokens),
  }
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const check = process.argv.includes('--check')
  let stale = false
  for (const [file, content] of Object.entries(outputs())) {
    const path = join(here, file)
    if (check) {
      let current = ''
      try {
        current = readFileSync(path, 'utf8')
      } catch {
        /* missing counts as stale */
      }
      if (current !== content) {
        console.error(`${file} is out of date. Run: make tokens`)
        stale = true
      }
    } else {
      mkdirSync(dirname(path), { recursive: true })
      writeFileSync(path, content)
      console.log(`wrote design/${file}`)
    }
  }
  process.exit(stale ? 1 : 0)
}
